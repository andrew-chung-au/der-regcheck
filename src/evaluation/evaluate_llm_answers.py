"""LLM evaluation harness for DER RegCheck answer configurations.

This module evaluates multiple prompt configurations (v1, v2, v3) using
a fixed set of 24 evaluation questions and an LLM judge.

Usage:
    # Generate answers for all prompt versions
    uv run python -m src.evaluation.evaluate_llm_answers \
      --mode generate \
      --overwrite

    # Judge the generated answers
    uv run python -m src.evaluation.evaluate_llm_answers \
      --mode judge

    # Generate summary report
    uv run python -m src.evaluation.summarise_llm_evaluation \
      --judge-scores data/evaluation/llm_judge_scores.jsonl \
      --output data/evaluation/llm_evaluation_summary.json
"""
from __future__ import annotations

import argparse
import json
import time
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import yaml

from pydantic import BaseModel, Field

from src.generation.citation_validator import validate_citations
from src.generation.prompts import get_prompt_instructions
from src.generation.schemas import StructuredAnswerOutput
from src.llm_client import generate_structured_answer, get_client
from src.retrieval.runtime_retriever import get_runtime_retriever


ROOT = Path(__file__).resolve().parents[2]
SCHEMA_VERSION = "1.0"


@dataclass
class EvaluationQuestion:
    """One evaluation question with metadata."""

    id: str
    category: str
    question: str
    expected_sources: list[str]
    expected_topics: list[str]
    expected_behavior: dict[str, Any]
    notes: str


class JudgeOutput(BaseModel):
    """Structured output schema for LLM judge."""

    groundedness_score: int = Field(ge=1, le=5)
    relevance_score: int = Field(ge=1, le=5)
    completeness_score: int = Field(ge=1, le=5)
    citation_quality_score: int = Field(ge=1, le=5)
    appropriate_uncertainty_score: int = Field(ge=1, le=5)
    rationale: str


JUDGE_INSTRUCTIONS = """You are evaluating answers generated by DER RegCheck, an evidence-first
RAG system for Distributed Energy Resource interconnection research.

Score each answer on the following dimensions from 1 (poor) to 5 (excellent):

**Groundedness (1-5):**
- 1: Material claims go beyond, conflict with, or are unsupported by supplied evidence
- 3: Most claims are grounded but some stretch the evidence
- 5: All claims accurately remain within supplied evidence and source-status limits

**Answer Relevance (1-5):**
- 1: Does not answer the actual research question
- 3: Addresses the question at a basic level
- 5: Comprehensively addresses the question at the appropriate level

**Completeness (1-5):**
- 1: Omits major supported aspects or required caveats
- 3: Covers most major points but omits some material conditions
- 5: Covers all material supported issues without irrelevant expansion

**Citation Quality (1-5):**
- 1: Missing, invalid, or misleading citations
- 3: Most material claims have citations but some are weak
- 5: Citations are claim-linked, valid, and distinguish authority appropriately

**Appropriate Uncertainty (1-5):**
- 1: Overconfident or unsafe when evidence is insufficient
- 3: Identifies some uncertainty but could be more specific
- 5: Clearly identifies uncertainty, limits, clarification needs, and decision boundaries

Return valid JSON matching the JudgeOutput schema. Provide a concise rationale."""


def load_yaml(path: Path) -> dict[str, Any]:
    """Load a YAML configuration file."""
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    """Load non-empty JSON Lines records."""
    return [
        json.loads(line)
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def append_jsonl(path: Path, records: list[dict[str, Any]]) -> None:
    """Append records to a JSONL checkpoint file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as output:
        for record in records:
            output.write(json.dumps(record) + "\n")


def now_iso() -> str:
    """Return current UTC timestamp in ISO format."""
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def load_evaluation_questions(path: Path) -> list[EvaluationQuestion]:
    """Load evaluation questions from YAML file."""
    data = load_yaml(path)
    questions = []

    for q in data.get("questions", []):
        questions.append(
            EvaluationQuestion(
                id=q["id"],
                category=q["category"],
                question=q["question"],
                expected_sources=q.get("expected_sources", []),
                expected_topics=q.get("expected_topics", []),
                expected_behavior=q.get("expected_behavior", {}),
                notes=q.get("notes", ""),
            )
        )

    return questions


def build_evidence_context(chunks: list[dict[str, Any]]) -> str:
    """Build the evidence pack supplied to the answer model."""
    sections: list[str] = []

    for index, chunk in enumerate(chunks, start=1):
        citation = chunk.get("citation") or {}
        source_policy = chunk.get("source_policy") or {}
        heading_path = " > ".join(chunk.get("heading_path") or [])
        section_ids = ".".join(
            str(item) for item in citation.get("section_ids") or []
        )

        sections.append(
            "\n".join(
                [
                    f"[S{index}]",
                    f"Source ID: {chunk.get('source_id', 'unknown')}",
                    f"Authority tier: {source_policy.get('authority_tier', 'unknown')}",
                    f"Currency status: {source_policy.get('currency_status', 'unknown')}",
                    f"Heading: {heading_path or 'Not available'}",
                    f"Section IDs: {section_ids or 'Not available'}",
                    f"PDF page: {citation.get('pdf_page_start', 'Not available')}",
                    "Evidence:",
                    chunk.get("evidence_text", "").strip(),
                ]
            )
        )

    return "\n\n---\n\n".join(sections)


def build_user_prompt(question: str, chunks: list[dict[str, Any]]) -> str:
    """Build the prompt containing the question and evidence pack."""
    evidence_context = build_evidence_context(chunks)
    labels = ", ".join(f"S{index}" for index in range(1, len(chunks) + 1))

    return f"""Original user question:
{question.strip()}


Retrieved evidence:
{evidence_context}


Return a structured answer to the original user question. For every factual
claim, set citation_labels only from this supplied-label set: {labels}.
Do not invent labels, source locations, page numbers, or document status."""


def get_git_commit() -> str:
    """Get current git commit hash."""
    import subprocess

    try:
        result = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            cwd=ROOT,
        )
        return result.stdout.strip()
    except Exception:
        return "unknown"


def generate_answer_with_prompt(
    *,
    question: str,
    sources: list[dict[str, Any]],
    prompt_version: str,
    llm_client: Any,
) -> tuple[StructuredAnswerOutput | None, Any, str]:
    """Generate an answer using a specific prompt configuration.

    Args:
        question: User question text.
        sources: Retrieved evidence chunks.
        prompt_version: One of 'v1_direct_rag', 'v2_structured_grounded_rag',
            or 'v3_few_shot_grounded_rag'.
        llm_client: Gemini client instance.

    Returns:
        Tuple of (parsed_output, usage_metadata, raw_text).
        Returns (None, None, error_message) on failure.
    """
    instructions = get_prompt_instructions(prompt_version)
    user_prompt = build_user_prompt(question, sources)

    try:
        output, usage = generate_structured_answer(
            instructions=instructions,
            user_prompt=user_prompt,
            output_type=StructuredAnswerOutput,
            client=llm_client,
            verbose=False,
        )
        return output, usage, ""
    except Exception as error:
        return None, None, f"{type(error).__name__}: {error}"


def main() -> None:
    """Parse arguments and run the LLM evaluation."""
    parser = argparse.ArgumentParser(description=__doc__)

    parser.add_argument(
        "--mode",
        choices=("generate", "judge"),
        default="generate",
        help="Evaluation mode. Default: generate.",
    )

    parser.add_argument(
        "--questions",
        type=Path,
        default=ROOT / "data/evaluation/llm_evaluation_questions.yaml",
        help="YAML file with evaluation questions.",
    )

    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "data/evaluation/llm_answers.jsonl",
        help="JSONL output path for answer generation.",
    )

    parser.add_argument(
        "--answers",
        type=Path,
        default=ROOT / "data/evaluation/llm_answers.jsonl",
        help="JSONL input file with answers to judge.",
    )

    parser.add_argument(
        "--judge-output",
        type=Path,
        default=ROOT / "data/evaluation/llm_judge_scores.jsonl",
        help="JSONL output path for judge scores.",
    )

    parser.add_argument(
        "--prompt-versions",
        type=str,
        default="v1_direct_rag,v2_structured_grounded_rag,v3_few_shot_grounded_rag",
        help="Comma-separated prompt versions to evaluate.",
    )

    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Delete output file before starting (generate mode only).",
    )

    args = parser.parse_args()

    if args.mode == "judge" and args.overwrite:
        parser.error("--overwrite is only valid for generate mode.")

    prompt_versions = [v.strip() for v in args.prompt_versions.split(",")]
    retriever = get_runtime_retriever()
    llm_client = get_client()
    git_commit = get_git_commit()
    run_id = f"llm_eval_{now_iso().replace(':', '-').replace('.', '-')}"

    if args.mode == "generate":
        if args.overwrite:
            args.output.unlink(missing_ok=True)
            print(f"Removed existing output: {args.output}")

        questions_path = (
            args.questions if args.questions.is_absolute() else ROOT / args.questions
        )
        output_path = args.output if args.output.is_absolute() else ROOT / args.output

        print(f"Loading evaluation questions from {questions_path}...")
        questions = load_evaluation_questions(questions_path)
        print(f"Loaded {len(questions)} questions.")

        if not questions:
            raise ValueError("No evaluation questions were found.")

        print(
            f"Mode: generate | "
            f"prompt_versions={prompt_versions} | "
            f"questions={len(questions)}"
        )

        all_records: list[dict[str, Any]] = []

        for q_idx, question in enumerate(questions, start=1):
            print(f"\nQuestion {q_idx}/{len(questions)}: {question.id} ({question.category})")

            # Retrieve evidence once for this question
            sources = retriever.retrieve(
                question=question.question,
                final_k=10,
            )

            evidence_labels = {
                f"S{i+1}": s["chunk_id"] for i, s in enumerate(sources)
            } if sources else {}

            for prompt_version in prompt_versions:
                print(f"  Generating answer for {prompt_version}...")

                start_time = time.perf_counter()

                if not sources:
                    # No evidence retrieved
                    record = {
                        "schema_version": SCHEMA_VERSION,
                        "run_id": run_id,
                        "question_id": question.id,
                        "category": question.category,
                        "question_text": question.question,
                        "prompt_version": prompt_version,
                        "git_commit": git_commit,
                        "retrieval_config_id": "vector_rerank_top10",
                        "retrieved_chunk_ids": [],
                        "evidence_labels": {},
                        "model_provider": "google_gemini",
                        "model_name": "gemini-3.5-flash-lite",
                        "generation_parameters": {"temperature": 0, "top_k": 10},
                        "raw_model_output": "",
                        "parsed_answer": {
                            "answer_status": "no_evidence_retrieved",
                        },
                        "latency_ms": 0,
                        "token_usage": None,
                        "generated_at_utc": now_iso(),
                    }
                    all_records.append(record)
                    continue

                output, usage, error = generate_answer_with_prompt(
                    question=question.question,
                    sources=sources,
                    prompt_version=prompt_version,
                    llm_client=llm_client,
                )

                elapsed_ms = int((time.perf_counter() - start_time) * 1000)

                if output is None:
                    record = {
                        "schema_version": SCHEMA_VERSION,
                        "run_id": run_id,
                        "question_id": question.id,
                        "category": question.category,
                        "question_text": question.question,
                        "prompt_version": prompt_version,
                        "git_commit": git_commit,
                        "retrieval_config_id": "vector_rerank_top10",
                        "retrieved_chunk_ids": [s["chunk_id"] for s in sources],
                        "evidence_labels": evidence_labels,
                        "model_provider": "google_gemini",
                        "model_name": "gemini-3.5-flash-lite",
                        "generation_parameters": {"temperature": 0, "top_k": 10},
                        "raw_model_output": "",
                        "parsed_answer": {
                            "answer_status": "generation_failed",
                            "error": error,
                        },
                        "latency_ms": elapsed_ms,
                        "token_usage": None,
                        "generated_at_utc": now_iso(),
                    }
                else:
                    # Validate citations deterministically
                    supplied_labels = {f"S{i+1}" for i in range(len(sources))}
                    validation = validate_citations(
                        answer=output,
                        supplied_evidence_labels=supplied_labels,
                    )

                    record = {
                        "schema_version": SCHEMA_VERSION,
                        "run_id": run_id,
                        "question_id": question.id,
                        "category": question.category,
                        "question_text": question.question,
                        "prompt_version": prompt_version,
                        "git_commit": git_commit,
                        "retrieval_config_id": "vector_rerank_top10",
                        "retrieved_chunk_ids": [s["chunk_id"] for s in sources],
                        "evidence_labels": evidence_labels,
                        "model_provider": "google_gemini",
                        "model_name": "gemini-3.5-flash-lite",
                        "generation_parameters": {"temperature": 0, "top_k": 10},
                        "raw_model_output": output.model_dump_json(),
                        "parsed_answer": output.model_dump(),
                        "latency_ms": elapsed_ms,
                        "token_usage": usage.model_dump() if usage else None,
                        "citation_validation": {
                            "is_valid": validation.is_valid,
                            "unknown_labels": list(validation.unknown_labels),
                            "uncited_claim_indexes": validation.uncited_claim_indexes,
                            "errors": validation.errors,
                        },
                        "generated_at_utc": now_iso(),
                    }

                all_records.append(record)

            # Checkpoint every 5 questions
            if q_idx % 5 == 0:
                append_jsonl(output_path, all_records)
                print(f"  Checkpointed {len(all_records)} records.")

        append_jsonl(output_path, all_records)
        print(f"\nLLM answer generation complete: {output_path}")
        print(f"Total records: {len(all_records)}")

    elif args.mode == "judge":
        answers_path = (
            args.answers if args.answers.is_absolute() else ROOT / args.answers
        )
        judge_output_path = (
            args.judge_output
            if args.judge_output.is_absolute()
            else ROOT / args.judge_output
        )

        print(f"Loading answers from {answers_path}...")
        answers = load_jsonl(answers_path)
        print(f"Loaded {len(answers)} answer records.")

        if not answers:
            raise ValueError("No answer records were found.")

        print(
            f"Mode: judge | "
            f"answers={len(answers)} | "
            f"judge_model=gemini-3.5-flash-lite"
        )

        judge_records: list[dict[str, Any]] = []

        for a_idx, answer_record in enumerate(answers, start=1):
            print(f"\nJudging {a_idx}/{len(answers)}: {answer_record['question_id']} ({answer_record['prompt_version']})")

            if not answer_record.get("raw_model_output"):
                print("  Skipping: no answer output to judge.")
                continue

            # Build judge prompt with question, answer, and evidence
            judge_prompt = f"""Question: {answer_record['question_text']}

Answer to evaluate:
{answer_record['raw_model_output']}

Score this answer using the evaluation rubric. Return valid JSON."""

            try:
                start_time = time.perf_counter()

                judge_output, judge_usage = generate_structured_answer(
                    instructions=JUDGE_INSTRUCTIONS,
                    user_prompt=judge_prompt,
                    output_type=JudgeOutput,
                    client=llm_client,
                    verbose=False,
                )

                elapsed_ms = int((time.perf_counter() - start_time) * 1000)

                composite = (
                    0.30 * judge_output.groundedness_score
                    + 0.20 * judge_output.relevance_score
                    + 0.20 * judge_output.completeness_score
                    + 0.20 * judge_output.citation_quality_score
                    + 0.10 * judge_output.appropriate_uncertainty_score
                )

                judge_record = {
                    "schema_version": SCHEMA_VERSION,
                    "run_id": f"llm_judge_{now_iso().replace(':', '-').replace('.', '-')}",
                    "answer_record_run_id": answer_record["run_id"],
                    "question_id": answer_record["question_id"],
                    "prompt_version": answer_record["prompt_version"],
                    "category": answer_record["category"],
                    "judge_model_provider": "google_gemini",
                    "judge_model_name": "gemini-3.5-flash-lite",
                    "groundedness_score": judge_output.groundedness_score,
                    "relevance_score": judge_output.relevance_score,
                    "completeness_score": judge_output.completeness_score,
                    "citation_quality_score": judge_output.citation_quality_score,
                    "appropriate_uncertainty_score": judge_output.appropriate_uncertainty_score,
                    "composite_score": round(composite, 4),
                    "judge_rationale": judge_output.rationale,
                    "judge_latency_ms": elapsed_ms,
                    "judged_at_utc": now_iso(),
                }

                judge_records.append(judge_record)
                print(
                    f"  G={judge_output.groundedness_score}, "
                    f"R={judge_output.relevance_score}, "
                    f"C={judge_output.completeness_score}, "
                    f"Q={judge_output.citation_quality_score}, "
                    f"U={judge_output.appropriate_uncertainty_score}, "
                    f"Composite={composite:.2f}"
                )

            except Exception as error:
                print(f"  Judge failed: {type(error).__name__}: {error}")
                continue

            # Checkpoint every 10 answers
            if a_idx % 10 == 0:
                append_jsonl(judge_output_path, judge_records)
                print(f"  Checkpointed {len(judge_records)} judge records.")

        append_jsonl(judge_output_path, judge_records)
        print(f"\nLLM judging complete: {judge_output_path}")
        print(f"Total judge records: {len(judge_records)}")


if __name__ == "__main__":
    main()